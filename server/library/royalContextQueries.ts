export function assertRoyalContextSearchBudget(): {
  total: number;
  byCategory: Record<string, number>;
} {
  const byCategory: Record<string, number> = {};
  let total = 0;
  for (const cat of ROYAL_CONTEXT_CATEGORIES) {
    const expected = BUDGET[cat.category];
    const actual = cat.queries.length;
    if (expected !== undefined && actual !== expected) {
      throw new Error(`Query budget mismatch for ${cat.category}: expected ${expected}, got ${actual}`);
    }
    byCategory[cat.category] = actual;
    total += actual;
  }
  if (total > 200) throw new Error(`Search budget exceeded: ${total}`);
  return { total, byCategory };
}

